"""Checkpoint checks and isolated input copies for resumed executions."""

import json
import pickle
import shutil
from hashlib import file_digest, sha256
from pathlib import Path

from sqlalchemy.orm import Session

from app.core.database import engine
from app.dataset.repository import Conflict
from app.training import repository
from app.training.models import TrainingTask


def availability(task: TrainingTask) -> dict:
    if task.status not in ("failed", "canceled"):
        return {"available": False, "reason": "只有失败或取消的任务可以恢复"}
    artifact = next((item for item in task.artifacts if item["id"] == "last"), None)
    if not task.snapshot or artifact is None:
        return {"available": False, "reason": "任务没有输入快照或最后检查点"}
    try:
        repository.artifact_file(task, "last")
        manifest = repository.task_dir(task.id) / task.snapshot["manifest_path"]
        if not manifest.is_file():
            return {"available": False, "reason": "任务的输入快照文件不存在"}
    except (LookupError, KeyError, ValueError):
        return {"available": False, "reason": "任务的最后检查点文件不存在"}
    return {"available": True, "reason": "提交后将校验检查点完整性和剩余轮次"}


def load_checkpoint(path: Path, expected_hash: str, total_epochs: int) -> tuple[dict, int]:
    import torch

    try:
        with path.open("rb") as source:
            if file_digest(source, "sha256").hexdigest() != expected_hash:
                raise Conflict("恢复检查点校验失败，文件已发生变化")
            source.seek(0)
            # Only allow a recorded, hash-checked checkpoint generated by this platform.
            checkpoint = torch.load(source, map_location="cpu", weights_only=False)
    except Conflict:
        raise
    except (OSError, RuntimeError, EOFError, ValueError, KeyError, pickle.UnpicklingError, AttributeError, TypeError) as exc:
        raise Conflict("无法读取恢复检查点，请使用复制配置新建训练") from exc
    if not isinstance(checkpoint, dict):
        raise Conflict("恢复检查点格式不正确")
    epoch = checkpoint.get("epoch")
    if type(epoch) is not int or epoch < 0 or epoch + 1 >= total_epochs:
        raise Conflict("检查点没有剩余训练轮次，或已被转换为仅含权重的模型")
    if (not isinstance(checkpoint.get("train_args"), dict) or checkpoint.get("optimizer") is None
            or checkpoint.get("model") is None and checkpoint.get("ema") is None):
        raise Conflict("检查点缺少优化器、模型或训练参数，不能恢复训练")
    return checkpoint, epoch


def validate_source(task: TrainingTask) -> tuple[dict, Path, int]:
    state = availability(task)
    if not state["available"]:
        raise Conflict(state["reason"])
    artifact, path = repository.artifact_file(task, "last")
    _, epoch = load_checkpoint(path, artifact["sha256"], task.config["epochs"])
    return artifact, path, epoch


def _checked_path(root: Path, relative: str) -> Path:
    path = (root / relative).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise Conflict("恢复训练的输入快照文件缺失")
    return path


def _verify_input(folder: Path, snapshot: dict, check) -> None:
    manifest_path = _checked_path(folder, "manifest.json")
    payload = manifest_path.read_bytes()
    if sha256(payload).hexdigest() != snapshot["digest"]:
        raise Conflict("恢复训练的输入快照校验失败")
    manifest = json.loads(payload)
    samples = _checked_path(folder, manifest["samples_path"])
    with samples.open("rb") as source:
        if file_digest(source, "sha256").hexdigest() != manifest["samples_sha256"]:
            raise Conflict("恢复训练的样本清单校验失败")
    with samples.open(encoding="utf-8") as source:
        for line in source:
            check()
            item = json.loads(line)
            for key in ("image", "label"):
                if f"{key}_path" not in item:
                    continue
                path = _checked_path(folder, item[f"{key}_path"])
                with path.open("rb") as sample:
                    if file_digest(sample, "sha256").hexdigest() != item[f"{key}_sha256"]:
                        raise Conflict("恢复训练的图片或标签校验失败")
    if manifest.get("data_sha256"):
        path = _checked_path(folder, "data.yaml")
        if sha256(path.read_bytes()).hexdigest() != manifest["data_sha256"]:
            raise Conflict("恢复训练的数据配置校验失败")


def prepare_resume(task: TrainingTask, directory: Path, check) -> dict:
    import torch

    with Session(engine()) as db:
        source = repository.get_task(db, task.resume_from_task_id)
        artifact, checkpoint_path, _ = validate_source(source)
        snapshot = dict(source.snapshot)
        root = repository.task_dir(source.id)
        input_directory = root / "input"
        _verify_input(input_directory, snapshot, check)
        checkpoint, epoch = load_checkpoint(checkpoint_path, task.resume_checkpoint["sha256"], task.config["epochs"])
    check()

    def copy_file(src, dest):
        check()
        return shutil.copyfile(src, dest)

    shutil.copytree(input_directory, directory / "input", copy_function=copy_file)
    _verify_input(directory / "input", snapshot, check)
    model_directory = directory / "model"
    model_directory.mkdir(exist_ok=True)
    model_path = model_directory / "last.pt"
    args = dict(checkpoint["train_args"])
    args.update(data=str(directory / snapshot["data_path"]), project=str(directory), name="output",
                save_dir=str(directory / "output"), exist_ok=True, device=task.config["deviceId"],
                batch=task.config["batchSize"], workers=task.config.get("workers", 0), amp=task.config.get("amp", False))
    checkpoint["train_args"] = args
    torch.save(checkpoint, model_path)
    check()
    with model_path.open("rb") as model:
        model_hash = file_digest(model, "sha256").hexdigest()
    return {**snapshot, "resume_model": "model/last.pt", "resume_sha256": model_hash, "epoch": epoch + 1}
